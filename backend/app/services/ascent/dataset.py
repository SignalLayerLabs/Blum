"""Reuse BLUM's bounded evidence repository with a stricter frozen-input adapter."""

from dataclasses import replace
from datetime import datetime, time
import hashlib
import json
import math
from types import SimpleNamespace

from app.services.trading_ml.dataset import TradingMLDatasetRepository
from app.services.trading_ml.features import TradingMLFeatureBuilder, IneligibleFeatureDataError
from .evaluation import utc_naive


def _number(value, *, name: str, maximum: float | None = None) -> float:
    if isinstance(value, bool) or not isinstance(value, (float, int)) or not math.isfinite(value) or value < 0:
        raise IneligibleFeatureDataError(f"INVALID_{name}")
    if maximum is not None and value > maximum:
        raise IneligibleFeatureDataError(f"INVALID_{name}")
    return float(value)


def _quality(value) -> float:
    result = _number(value, name="QUALITY", maximum=100)
    if result < 70:
        raise IneligibleFeatureDataError("INSUFFICIENT_DATA_QUALITY")
    return result


def _frozen_timestamps(value, decision: datetime, key: str = "") -> None:
    if isinstance(value, dict):
        for name, nested in value.items():
            _frozen_timestamps(nested, decision, name)
    elif isinstance(value, list):
        for nested in value:
            _frozen_timestamps(nested, decision, key)
    elif isinstance(value, str) and ("timestamp" in key.lower() or key.lower() in ("as_of", "date")):
        try:
            timestamp = datetime.fromisoformat(value.replace("Z", "+00:00"))
        except ValueError as exc:
            raise IneligibleFeatureDataError("INVALID_INPUT_TIMESTAMP") from exc
        if utc_naive(timestamp) > utc_naive(decision):
            raise IneligibleFeatureDataError("FUTURE_INPUT_TIMESTAMP")


class FrozenConfidenceBuilder(TradingMLFeatureBuilder):
    def __init__(self):
        self.provenance: dict[str, dict] = {}

    def from_equity(self, prediction, outcome):
        # HistoricalPrediction is generated by historical sampling, never proof of a forward decision.
        if prediction.model_version_used != "base-static":
            raise IneligibleFeatureDataError("UNVERIFIED_HISTORICAL_MODEL_AVAILABILITY")
        for memory in (prediction.learning_memory_used, prediction.strategy_memory_used, prediction.research_priority_used):
            memory = memory or {}
            if memory.get("confidence_delta", 0) or memory.get("rows") or memory.get("signal_performance"):
                raise IneligibleFeatureDataError("UNVERIFIED_HISTORICAL_MEMORY_AVAILABILITY")
        # created_at is the replay job's wall clock, not historical market time.
        frozen_prediction = SimpleNamespace(**{key: getattr(prediction, key) for key in (
            "id", "ticker", "analysis_date", "initial_price", "expected_direction", "confidence",
            "data_quality_score", "market_regime", "volatility_regime", "sector",
            "point_in_time_context", "prediction_payload")},
            created_at=datetime.combine(prediction.analysis_date, time.max))
        row = super().from_equity(frozen_prediction, outcome)
        # The historical learning ledger deliberately stores its outcome frame
        # alongside the prediction context. It is excluded, never a feature.
        frozen_context = {key: value for key, value in (prediction.point_in_time_context or {}).items()
                          if key not in ("future_prices", "evaluation_data_availability")}
        _frozen_timestamps(frozen_context, row.decision_timestamp)
        _frozen_timestamps(prediction.prediction_payload, row.decision_timestamp)
        cost = _number((outcome.metrics_payload or {}).get("modeled_cost_r"), name="COST")
        confidence = _number(prediction.confidence, name="CONFIDENCE", maximum=100)
        confidence = confidence * 100 if confidence <= 1 else confidence
        uid = f"{row.source_object_type}:{row.source_object_id}"
        self.provenance[uid] = {"source": "historical_learning_loop", "model_version": prediction.model_version_used,
            "input_hash": hashlib.sha256(json.dumps(prediction.point_in_time_context, sort_keys=True).encode()).hexdigest(),
            "cost_model": "stored_modeled_cost_r", "excluded_outcome_fields": ["future_prices", "evaluation_data_availability"]}
        return replace(row, evidence_lane="REPLAY_EVIDENCE", features={"confidence": confidence,
            "data_quality_score": _quality(prediction.data_quality_score), "expected_cost": cost})

    def from_replay(self, trade):
        decision = dict(trade.decision_payload or {})
        # State transitions record later exits; they are audit data, never candidate inputs.
        _frozen_timestamps({key: value for key, value in decision.items() if key != "state_transitions"}, trade.decision_timestamp)
        frozen = SimpleNamespace(**{key: getattr(trade, key) for key in (
            "id", "r_multiple", "exit_timestamp", "decision_timestamp", "market", "setup_type", "timeframe",
            "ticker", "data_quality_score", "evidence_type", "benchmark_excess")},
            decision_payload=decision, execution_payload={}, outcome_payload={})
        row = super().from_replay(frozen)
        confidence = _number(row.features.get("confidence"), name="CONFIDENCE", maximum=100)
        profile = (trade.execution_payload or {}).get("cost_profile") or {}
        if profile.get("execution_model") != "realistic_execution_v1":
            raise IneligibleFeatureDataError("MISSING_COST_PROVENANCE")
        cost = _number(profile.get("total_round_trip_bps"), name="COST")
        self.provenance[f"{row.source_object_type}:{row.source_object_id}"] = {
            "source": "hyperbolic_replay", "strategy_fingerprint": trade.strategy_fingerprint,
            "input_hash": hashlib.sha256(json.dumps(decision, sort_keys=True).encode()).hexdigest(),
            "cost_model": profile}
        return replace(row, features={"confidence": confidence,
            "data_quality_score": _quality(trade.data_quality_score), "expected_cost": cost})

    def from_forex(self, decision, evidence):
        row = super().from_forex(decision, evidence)
        payload = evidence.payload_json or {}
        # A realized Forex result without an explicit net-cost contract is ineligible here.
        if not payload.get("net_cost_adjusted"):
            raise IneligibleFeatureDataError("MISSING_NET_COST_CONTRACT")
        cost = _number(payload.get("modeled_cost_r"), name="COST")
        quality = _quality(row.features.get("data_quality_score"))
        _number(row.features.get("confidence"), name="CONFIDENCE", maximum=100)
        self.provenance[f"{row.source_object_type}:{row.source_object_id}"] = {
            "source": "forex_frozen_decision", "strategy_id": decision.strategy_id, "cost_model": "stored_net_cost_contract"}
        return replace(row, features={"confidence": row.features["confidence"],
            "data_quality_score": quality, "expected_cost": cost})


class AscentDatasetRepository(TradingMLDatasetRepository):
    def __init__(self):
        self.frozen_builder = FrozenConfidenceBuilder()
        super().__init__(builder=self.frozen_builder)
